class Command(BaseCommand):
    help = "پلن‌ها، صفحات، پرسش‌های متداول و قالب‌های آماده"

    def add_arguments(self, parser):
        parser.add_argument("--overwrite", action="store_true")

    def handle(self, *args, **opts):
        SiteSettings.load()
        for p in PLANS:
            Plan.objects.get_or_create(slug=p["slug"], defaults=p)
        for i, (q, a) in enumerate(FAQS):
            FAQ.objects.get_or_create(question=q, defaults={"answer": a, "order": i})
        for i, (t, slug, body) in enumerate(PAGES):
            Page.objects.get_or_create(slug=slug, defaults={"title": t, "body": body, "order": i})
        made = 0
        for i, (slug, title, cat, emoji, featured, desc, fn) in enumerate(TEMPLATES):
            data = engine.clean_schema(fn())
            obj = Template.objects.filter(slug=slug).first()
            if obj and not opts["overwrite"]:
                continue
            Template.objects.update_or_create(slug=slug, defaults={"title": title, "category": cat, "emoji": emoji, "is_featured": featured,
                                                                   "description": desc, "schema": data, "order": i, "is_active": True})
            made += 1
        self.stdout.write(self.style.SUCCESS(f"✓ پلن‌ها، صفحات و {made} قالب آماده"))
