_n = 0


def _id(p="q"):
    global _n
    _n += 1
    return f"{p}_{_n:03d}"


def Q(t, title, required=True, desc="", **opt):
    show_if = opt.pop("show_if", None)
    jumps = opt.pop("jumps", [])
    qid = opt.pop("id", None) or _id()
    return {"id": qid, "type": t, "title": title, "description": desc, "required": required and t != "statement",
            "image": "", "opt": opt, "show_if": show_if, "jumps": jumps}


def C(*labels, scores=None):
    return [{"id": _id("c"), "label": lbl, "score": (scores[i] if scores else 0)} for i, lbl in enumerate(labels)]


def cond(src, op, value=""):
    return {"src": src, "op": op, "value": value}


def when(*conds, match="all"):
    return {"match": match, "conds": list(conds)}


def schema(title, text, questions, endings=None, variables=None, calcs=None, theme=None, button="شروع"):
    s = engine.default_schema()
    s["welcome"].update({"title": title, "text": text, "button": button})
    s["questions"] = questions
    if endings:
        s["endings"] = endings
    s["variables"] = variables or []
    s["calcs"] = calcs or []
    if theme:
        s["theme"].update(theme)
    return s


def ending(eid, title, text, when_=None, show_score=False):
    return {"id": eid, "title": title, "text": text, "button_text": "", "button_url": "", "redirect_url": "",
            "show_score": show_score, "when": when_}


